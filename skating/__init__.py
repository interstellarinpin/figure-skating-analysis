"""
skating
=======

A physics-first toolkit for analyzing figure skating jumps: the geometry of
mid-air reorientation, video-based pose kinematics, forward simulation, and
motion planning.

The intellectual core lives in :mod:`skating.physics`, which treats a skater's
mid-air rotation the way the "gauge theory of the falling cat" treats a cat:
as motion generated by *changing shape*, bookkept by a connection on the space
of body shapes. See ``docs/theory/gauge-theory-of-skating.md``.

Subpackages
-----------
physics
    Rigid-body inertia, angular momentum, and the geometric-phase (connection /
    holonomy) machinery that explains the "snap."
sim
    Minimal, honest forward models: a planar falling-cat reorientation and a
    full jump that layers a geometric phase on top of a real (L != 0) spin.
video
    Monocular pose extraction and the kinematics that turn joint tracks into
    moment-of-inertia and rotation-rate estimates.
planning
    Trajectory optimization for a physically valid jump, framed against the
    motion-planning / VLA skill-library approach from the robopolicy work.
"""

